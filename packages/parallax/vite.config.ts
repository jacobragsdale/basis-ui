import babel from "@rolldown/plugin-babel";
import { basisPlugins, basisTest } from "@basis/ui/preset";
import { reactCompilerPreset } from "@vitejs/plugin-react";
import { fileURLToPath } from "node:url";

import { defineConfig } from "vite-plus";

// The Rust the engine is built from: the wasm task runs again only when one of these changes.
const rust = [
  "crates/**",
  "Cargo.toml",
  "Cargo.lock",
  "rust-toolchain.toml",
  ".cargo/config.toml",
  "scripts/build-wasm.ts",
];

export default defineConfig({
  pack: {
    dts: {
      generator: "tsgo",
    },
    entry: ["src/index.ts", "src/worker.ts"],
    /* The worker's bundle loads the engine from beside itself, where wasm-bindgen's glue looks for it, so an app's
     * bundler finds it as an asset of the worker. */
    copy: [{ from: "wasm/parallax_wasm_bg.wasm", to: "dist" }],
    plugins: [
      /* The built package starts the worker shipped beside it; its source, which the harnesses build, has none, and
       * Vite would fail to bundle a worker URL that finds nothing. */
      {
        name: "parallax:packaged-worker",
        resolveId: (source: string): string | null =>
          source === "#engine/packaged-worker.ts"
            ? fileURLToPath(new URL("src/engine/packaged-worker.build.ts", import.meta.url))
            : null,
      },
      // The React Compiler, as `@basis/ui` builds with it: a hook that breaks the rules of React fails the build.
      babel({
        presets: [
          reactCompilerPreset({
            environment: { enableResetCacheOnSourceFileChanges: false },
            panicThreshold: "all_errors",
          }),
        ],
      }),
    ],
  },
  plugins: basisPlugins(),
  run: {
    tasks: {
      /* The scale harness (tests/perf/bench.ts): trades and positions at 150,000, 1,000,000 and 2,000,000 rows in
       * headless Chromium, plain and under a CPU quota, against tests/perf/budgets.json. Arguments go to the bench,
       * such as --sizes 150000 --modes plain. Never cached: it measures this machine as it is now. */
      bench: { cache: false, command: "node tests/perf/bench.ts", dependsOn: ["build"] },
      build: { command: "vp pack", dependsOn: ["wasm"] },
      // The charts' end-to-end specs, in the pinned Playwright image (tests/e2e/charts/run.ts); never cached, as they drive
      // a browser against a build of the harness.
      "charts-e2e": { cache: false, command: "node tests/e2e/charts/run.ts", dependsOn: ["wasm"] },
      /* The grid's end-to-end specs, in the pinned Playwright image, against the harness: Docker and the Rust toolchain
       * are needed. Arguments go to Playwright, such as spec names or --update-snapshots. It is never cached, so it sees
       * the whole environment, such as PARALLAX_PREBUILT and CARGO_TARGET_DIR. */
      "grid-e2e": { cache: false, command: "bash tests/e2e/grid/in-image.sh", dependsOn: ["wasm"] },
      /* The pivot's end-to-end specs, the same way against a harness of its own: its settings, menus, filters, the
       * rows behind a value, links, screenshots, and its canvas against the Angular pivot's. */
      "pivot-e2e": {
        cache: false,
        command: "bash tests/e2e/pivot/in-image.sh",
        dependsOn: ["wasm"],
      },
      /* The protocol's TypeScript, src/proto/parallax_pb.ts, generated by buf with protoc-gen-es from the .proto the
       * Rust compiles. It is committed, and CI fails when this task changes it. */
      proto: {
        cache: {
          input: ["crates/parallax-protocol/proto/**", "buf.gen.yaml"],
          output: ["src/proto/**"],
        },
        command: "buf generate",
      },
      // The browser tests run the built worker too, as an app gets it.
      test: { command: "vp test", dependsOn: ["build"] },
      wasm: {
        cache: {
          // What changes the module, and where cargo and rustup keep their files, which tasks otherwise never see.
          env: ["CARGO_BUILD_JOBS", "RUSTFLAGS"],
          input: rust,
          output: ["wasm/**"],
          untrackedEnv: ["CARGO_HOME", "CARGO_TARGET_DIR", "RUSTUP_HOME", "RUSTUP_TOOLCHAIN"],
        },
        command: "node scripts/build-wasm.ts",
      },
    },
  },
  test: {
    projects: [
      // The core's logic, in Node.
      { extends: true, test: { include: ["tests/unit/**/*.test.ts"], name: "unit" } },
      // The engine's real worker, the theme's CSS and the React layer, in Chromium.
      {
        extends: true,
        test: {
          include: ["tests/browser/**/*.test.{ts,tsx}"],
          name: "browser",
          ...(await basisTest()),
        },
      },
    ],
  },
});

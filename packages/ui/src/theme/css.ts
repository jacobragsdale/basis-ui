// Turns the inputs, ramps and tokens into the theme's CSS. `scripts/build-theme.ts` writes it to
// `src/styles/theme.css`, and a test fails when the committed file differs from what this produces.

import { parse, type Color, type Oklch } from "culori";

import { fonts, radius, spacing } from "./inputs.ts";
import { rampStep, tone, type Mode } from "./ramps.ts";
import { tokens, type Source } from "./tokens.ts";

/** A token source's colour in a mode, as culori reads it. */
export function resolve(source: Source, inMode: Mode): Color {
  if ("css" in source) {
    const parsed = parse(source.css);
    if (parsed === undefined) {
      throw new TypeError(`The theme colour ${source.css} is not CSS that culori can read.`);
    }
    return parsed;
  }
  if ("step" in source) {
    return rampStep(source.hue, inMode, source.step);
  }
  return tone(source.hue, source.lightness);
}

/** A token's colour in a mode. */
export function colourOf(name: string, inMode: Mode): Color {
  const token = tokens[name];
  if (token === undefined) {
    throw new RangeError(`The theme has no token named ${name}.`);
  }
  return resolve(token[inMode], inMode);
}

function round(value: number | undefined, digits: number): string {
  return Number((value ?? 0).toFixed(digits)).toString();
}

function format(source: Source, inMode: Mode): string {
  if ("css" in source) {
    return source.css;
  }
  const colour = resolve(source, inMode) as Oklch;
  return `oklch(${round(colour.l, 3)} ${round(colour.c, 4)} ${round(colour.h, 1)})`;
}

function declarations(inMode: Mode): string {
  return Object.entries(tokens)
    .map(([name, token]) => `  --${name}: ${format(token[inMode], inMode)};`)
    .join("\n");
}

const header = `/* Generated by scripts/build-theme.ts from src/theme; do not edit it by hand. Change src/theme/inputs.ts, run
   \`vp run @basis/ui#theme\`, and let the theme's tests say whether the result still passes. */`;

/** The theme's whole stylesheet. */
export function themeCss(): string {
  const colourMappings = Object.keys(tokens)
    .map((name) => `  --color-${name}: var(--${name});`)
    .join("\n");
  return `${header}

@import "@fontsource-variable/inter";
@import "@fontsource-variable/jetbrains-mono";

/* Tokens switch with the mode, so \`dark:\` variants have nothing to do. This keeps any that slip in on the user's
   chosen mode rather than the operating system's. */
@custom-variant dark (&:where(.dark, .dark *));

:root {
  color-scheme: light;
  --radius: ${radius};
${declarations("light")}
}

.dark {
  color-scheme: dark;
${declarations("dark")}
}

/* The compact density shrinks the spacing unit, and every spacing utility and control height with it. */
:root[data-density="compact"] {
  --spacing: ${spacing.compact};
}

/* Only the theme's own values exist: Tailwind's palette, its blur utilities and most of its shadows are removed, so a
   class that uses them is an unknown class and fails the lint. Citrix desktops draw on the CPU, where blur is slow. */
@theme {
  --color-*: initial;
  --blur-*: initial;
  --shadow-*: initial;
  --inset-shadow-*: initial;
  --drop-shadow-*: initial;
  --text-shadow-*: initial;
  --radius-*: initial;
  --shadow-sm: 0 1px 2px 0 oklch(0 0 0 / 0.06);
  --shadow-md: 0 2px 6px -1px oklch(0 0 0 / 0.1);
  --spacing: ${spacing.comfortable};
  --text-2xs: 0.625rem;
  --text-2xs--line-height: 0.875rem;
  --font-sans: ${fonts.sans};
  --font-mono: ${fonts.mono};
  --default-transition-duration: 120ms;
}

@theme inline {
  --radius-sm: calc(var(--radius) * 0.6);
  --radius-md: calc(var(--radius) * 0.8);
  --radius-lg: var(--radius);
  --radius-xl: calc(var(--radius) * 1.4);
${colourMappings}
}

@media (prefers-reduced-motion: reduce) {
  *,
  ::before,
  ::after {
    animation-duration: 0.01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important;
  }
}
`;
}

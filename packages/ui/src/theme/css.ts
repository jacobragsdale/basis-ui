// Turns the inputs, ramps and tokens into the theme's CSS. `scripts/build-theme.ts` writes it to
// `src/styles/theme.css`, and a test fails when the committed file differs from what this produces.

import { parse } from "culori";
import type { Color, Oklch } from "culori";

import {
  controls,
  disabledOpacity,
  durations,
  focusRing,
  fonts,
  layers,
  pillRadius,
  radius,
  shadows,
  spacing,
  targetSize,
} from "./inputs.ts";
import { rampStep, tone } from "./ramps.ts";
import type { ControlSize, ControlSizeName } from "./inputs.ts";
import type { Mode } from "./ramps.ts";
import { tokens } from "./tokens.ts";
import type { Source } from "./tokens.ts";

/** A source on one of the theme's hues: a ramp step, or a lightness. */
type HueSource = Exclude<Source, { readonly css: string }>;

/** The decimal places the stylesheet writes each OKLCH channel with. */
const places = { chroma: 4, hue: 1, lightness: 3 } as const;

/** A hue source's colour in a mode, with its alpha when it has one. */
function toneOf(source: HueSource, inMode: Mode): Oklch {
  if ("step" in source) {
    const colour = rampStep(source.hue, inMode, source.step);
    return source.alpha === undefined ? colour : { ...colour, alpha: source.alpha };
  }
  return tone(source.hue, source.lightness);
}

/** A token source's colour in a mode, as culori reads it. */
function resolve(source: Source, inMode: Mode): Color {
  if ("css" in source) {
    const parsed = parse(source.css);
    if (parsed === undefined) {
      throw new TypeError(`The theme colour ${source.css} is not CSS that culori can read.`);
    }
    return parsed;
  }
  return toneOf(source, inMode);
}

/** A token's colour in a mode. */
function colourOf(name: string, inMode: Mode): Color {
  const token = tokens[name];
  if (token === undefined) {
    throw new RangeError(`The theme has no token named ${name}.`);
  }
  return resolve(token[inMode], inMode);
}

function round(value: number | undefined, digits: number): string {
  return Number((value ?? 0).toFixed(digits)).toString();
}

function format(source: Source, inMode: Mode): string {
  if ("css" in source) {
    return source.css;
  }
  const colour = toneOf(source, inMode);
  const lightness = round(colour.l, places.lightness);
  const chroma = round(colour.c, places.chroma);
  const hue = round(colour.h, places.hue);
  const alpha = colour.alpha === undefined ? "" : ` / ${String(colour.alpha)}`;
  return `oklch(${lightness} ${chroma} ${hue}${alpha})`;
}

function declarations(inMode: Mode): string {
  return Object.entries(tokens)
    .map(([name, token]) => `  --${name}: ${format(token[inMode], inMode)};`)
    .join("\n");
}

const header = `/* Generated by scripts/build-theme.ts from src/theme; do not edit it by hand. Change src/theme/inputs.ts, run
   \`vp run @basis/ui#theme\`, and let the theme's tests say whether the result still passes. */`;

/** The face with tabular figures: \`@fontsource-variable/inter\`'s Latin file, the one that holds the figures, and the
 * name of the copy beside the stylesheet. */
const tabularFace = {
  file: "inter-latin-wght-normal.woff2",
  source: "@fontsource-variable/inter/files/inter-latin-wght-normal.woff2",
} as const;

const fontsAndVariant = `@import "@fontsource-variable/inter";
@import "@fontsource-variable/jetbrains-mono";

/* Inter's Latin file again, under the name \`--font-num\` gives it, with tabular figures on, so that a canvas, which
   cannot ask for them, draws digits of one width. Chrome honours the descriptor from version 139, and parallax's
   browser tests measure that it does. Text outside these characters falls through to Inter Variable, the next face in
   the stack, whose other files hold no figures. The file is a copy of the package's, which \`vp run @basis/ui#theme\`
   makes, since a stylesheet can name a file in a package only by a relative URL. */
@font-face {
  font-family: "Inter Tabular";
  font-style: normal;
  font-display: swap;
  font-weight: 100 900;
  font-feature-settings: "tnum";
  src: url("./fonts/${tabularFace.file}") format("woff2-variations");
  unicode-range:
    U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329,
    U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD;
}

/* Tokens switch with the mode, so \`dark:\` variants have nothing to do. This keeps any that slip in on the user's
   chosen mode rather than the operating system's. */
@custom-variant dark (&:where(.dark, .dark *));

/* Motion stops where the operating system asks for less of it, and where the user's \`motion\` preference is
   \`reduced\`, which the preferences put on the root element as \`data-motion\`, for a desktop whose Windows setting is
   not the user's to change. \`motion-reduce:\` and \`motion-safe:\` follow both. */
@custom-variant motion-reduce {
  @media (prefers-reduced-motion: reduce) {
    @slot;
  }
  &:where([data-motion="reduced"] *) {
    @slot;
  }
}
@custom-variant motion-safe {
  @media (prefers-reduced-motion: no-preference) {
    &:not(:where([data-motion="reduced"] *)) {
      @slot;
    }
  }
}`;

/** The pixels in a rem, at the browser's default font size. */
const pixelsPerRem = 16;

/** The control sizes, from the smallest. */
const controlSizes: readonly ControlSizeName[] = ["xs", "sm", "md", "lg"];

/** Where the text starts in a control whose icon sits at its start: the inset beside the icon, the icon and the gap. A
 * menu's item without an icon is indented by it, so that its text lines up with its neighbours'. */
function indentOf({ insetBesideIcon, icon, gap }: ControlSize): number {
  return insetBesideIcon + icon + gap;
}

/** A length in pixels as rem, which is whole pixels at the default font size. */
function rem(pixels: number): string {
  return `${String(pixels / pixelsPerRem)}rem`;
}

/** A control size's lengths, each by the name its variable takes after the size. */
function lengthsOf(lengths: ControlSize): readonly (readonly [string, number])[] {
  return [
    ["gap", lengths.gap],
    ["height", lengths.height],
    ["icon", lengths.icon],
    ["inset", lengths.inset],
    ["inset-icon", lengths.insetBesideIcon],
    ["indent", indentOf(lengths)],
  ];
}

/** One density's control lengths as declarations. A component reads them as `h-(--control-md-height)`,
 * `px-(--control-md-inset)`, `pl-(--control-md-inset-icon)`, `size-(--control-md-icon)` and `gap-(--control-md-gap)`:
 * variables, not named utilities, so that `cn` merges an app's `h-9` or `size-6` over them, where it would keep both of
 * two named ones. */
function controlDeclarations(density: keyof typeof controls): string {
  return controlSizes
    .flatMap((size) =>
      lengthsOf(controls[density][size]).map(
        ([name, pixels]) => `  --control-${size}-${name}: ${rem(pixels)};`,
      ),
    )
    .join("\n");
}

/** The tokens in each mode, and the control lengths in each density. Compact, the default density, is the base, so a
 * page that no script has touched shows it; `data-density="comfortable"` puts the comfortable density's spacing unit
 * and control lengths in its place. The radius, the focus ring and the shadows are variables here, rather than values
 * Tailwind writes into each utility, so that a theme can change them at run time. */
function modes(): string {
  return `:root {
  color-scheme: light;
  --radius: ${radius};
  --font-num: ${fonts.num};
  --focus-width: ${focusRing.width};
  --focus-offset: ${focusRing.offset};
  --shadow-raised: ${shadows.raised};
  --shadow-floating: ${shadows.floating};
${controlDeclarations("compact")}
${declarations("light")}
}

.dark {
  color-scheme: dark;
${declarations("dark")}
}

/* The comfortable density widens the spacing unit, and every spacing utility with it, and sets its own control
   lengths. */
:root[data-density="comfortable"] {
  --spacing: ${spacing.comfortable};
${controlDeclarations("comfortable")}
}`;
}

/** Tailwind's theme: only the theme's own values, and a colour utility for every token. */
function scales(): string {
  const colourMappings = Object.keys(tokens)
    .map((name) => `  --color-${name}: var(--${name});`)
    .join("\n");
  return `/* Only the theme's own values exist: Tailwind's palette, its blur utilities and most of its shadows are removed, so a
   class that uses them is an unknown class and fails the lint. Citrix desktops draw on the CPU, where blur is slow.
   Each scale is named for its use: \`duration-popup\` and \`duration-panel\`, \`z-raised\` and \`z-popup\`,
   \`rounded-pill\` and \`opacity-disabled\`. */
@theme {
  --color-*: initial;
  --blur-*: initial;
  --shadow-*: initial;
  --inset-shadow-*: initial;
  --drop-shadow-*: initial;
  --text-shadow-*: initial;
  --radius-*: initial;
  --radius-pill: ${pillRadius};
  --opacity-disabled: ${disabledOpacity};
  --z-index-raised: ${layers.raised};
  --z-index-popup: ${layers.popup};
  --spacing: ${spacing.compact};
  --spacing-target: ${targetSize};
  --text-2xs: 0.625rem;
  --text-2xs--line-height: 0.875rem;
  --font-sans: ${fonts.sans};
  --font-mono: ${fonts.mono};
  --default-transition-duration: ${durations.control};
  --transition-duration-popup: ${durations.popup};
  --transition-duration-panel: ${durations.panel};
}

/* A bare \`outline\` or \`ring\` is the focus ring's width. A focus ring is
   \`outline-solid outline outline-offset-(--focus-offset) outline-ring\` under \`focus-visible:\`: an outline, whose
   offset is transparent on any surface and which Windows' forced colours keep. Its width and offset stay variables,
   since \`cn\` would take a named width for a second colour and drop it. */
@theme inline {
  --default-outline-width: var(--focus-width);
  --default-ring-width: var(--focus-width);
  --shadow-sm: var(--shadow-raised);
  --shadow-md: var(--shadow-floating);
  --radius-sm: calc(var(--radius) * 0.6);
  --radius-md: calc(var(--radius) * 0.8);
  --radius-lg: var(--radius);
  --radius-xl: calc(var(--radius) * 1.4);
${colourMappings}
}`;
}

/* Under reduced motion, from the operating system or the user's preference, nothing moves: every transition and
 * animation ends at once, the sidebar's slide and an accordion's opening among them. While the theme, mode or
 * density changes, nothing transitions at all: `applyPreferences` sets `data-switching` for the frame that shows the
 * change, so the page changes in one frame, as its canvases do, rather than cross-fading every control. */
const reducedMotion = `@media (prefers-reduced-motion: reduce) {
  *,
  ::before,
  ::after {
    animation-duration: 0.01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important;
  }
}

:root[data-motion="reduced"] *,
:root[data-motion="reduced"] ::before,
:root[data-motion="reduced"] ::after {
  animation-duration: 0.01ms !important;
  animation-iteration-count: 1 !important;
  transition-duration: 0.01ms !important;
}

:root[data-switching] *,
:root[data-switching] ::before,
:root[data-switching] ::after {
  transition: none !important;
}`;

/** The theme's whole stylesheet. */
function themeCss(): string {
  return `${[header, fontsAndVariant, modes(), scales(), reducedMotion].join("\n\n")}\n`;
}

export { colourOf, resolve, tabularFace, themeCss };

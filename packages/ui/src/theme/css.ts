// The generator: turns themes' inputs, through their ramps and tokens, into the theme's CSS. Each function is a pure
// function of a theme's inputs. `scripts/build-theme.ts` writes the shipped themes to `src/styles/theme.css`, and a
// test fails when the committed file differs from what this produces.

import { tokenDeclarations } from "./colours.ts";
import { controlDeclarations, scaleDeclarations, shadowDeclarations } from "./declarations.ts";
import type { ThemeInputs } from "./inputs.ts";
import { tokensOf } from "./tokens.ts";

const header = `/* Generated by scripts/build-theme.ts from src/theme; do not edit it by hand. Change a theme's inputs in
   src/theme/themes, run \`vp run @basis/ui#theme\`, and let \`vp check\` say whether each passes \`checkTheme\`. */`;

/** The face with tabular figures: \`@fontsource-variable/inter\`'s Latin file, the one that holds the figures, and the
 * name of the copy beside the stylesheet. */
const tabularFace = {
  file: "inter-latin-wght-normal.woff2",
  source: "@fontsource-variable/inter/files/inter-latin-wght-normal.woff2",
} as const;

const fontsAndVariant = `@import "@fontsource-variable/inter";
@import "@fontsource-variable/jetbrains-mono";

/* Inter's Latin file again, under the name \`--font-num\` gives it, with tabular figures on, so that a canvas, which
   cannot ask for them, draws digits of one width. Chrome honours the descriptor from version 139, and parallax's
   browser tests measure that it does. Text outside these characters falls through to Inter Variable, the next face in
   the stack, whose other files hold no figures. The file is a copy of the package's, which \`vp run @basis/ui#theme\`
   makes, since a stylesheet can name a file in a package only by a relative URL. */
@font-face {
  font-family: "Inter Tabular";
  font-style: normal;
  font-display: swap;
  font-weight: 100 900;
  font-feature-settings: "tnum";
  src: url("./fonts/${tabularFace.file}") format("woff2-variations");
  unicode-range:
    U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329,
    U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD;
}

/* Tokens switch with the mode, so \`dark:\` variants have nothing to do. This keeps any that slip in on the user's
   chosen mode rather than the operating system's. */
@custom-variant dark (&:where(.dark, .dark *));

/* Motion stops where the operating system asks for less of it, and where the user's \`motion\` preference is
   \`reduced\`, which the preferences put on the root element as \`data-motion\`, for a desktop whose Windows setting is
   not the user's to change. \`motion-reduce:\` and \`motion-safe:\` follow both. */
@custom-variant motion-reduce {
  @media (prefers-reduced-motion: reduce) {
    @slot;
  }
  &:where([data-motion="reduced"] *) {
    @slot;
  }
}
@custom-variant motion-safe {
  @media (prefers-reduced-motion: no-preference) {
    &:not(:where([data-motion="reduced"] *)) {
      @slot;
    }
  }
}`;

/** The radius of a pill, such as a badge or a switch's track: a half-circle at each end, whatever its length. It is
 * geometry, the same in every theme. */
const pillRadius = "9999px";

/** The stacking order: a part raised over its siblings, such as a focused button in a group, and a popup or the veil
 * behind a dialog, over the page. It is structure, the same in every theme. */
const layers = { popup: "50", raised: "10" } as const;

/** The smallest a control may be, across and down: WCAG 2.2's minimum target size, 24 CSS pixels, which no theme may
 * lower. It is a fixed length rather than a multiple of the spacing unit, so the compact density cannot shrink it. It
 * gives `min-h-target` and `min-w-target`, which every control that could be shorter carries. */
const targetSize = "1.5rem";

/** Where a theme's three blocks apply: its base, its dark mode and its comfortable density. */
interface Selectors {
  readonly base: string;
  readonly dark: string;
  readonly comfortable: string;
}

/** The default theme's selectors: the page's root, the mode's class wherever it is, and the density on the root. */
const defaultSelectors: Selectors = {
  base: ":root",
  comfortable: ':root[data-density="comfortable"]',
  dark: ".dark",
};

/** Another theme's selectors. A theme and the mode's class may sit on one element or either may sit inside the other,
 * such as a wrapper that shows a theme on a dark page, or a dark panel in a themed page, and each case is the theme's
 * dark mode. A theme inside `.dark`, or on the same element, weighs two classes, an attribute weighing as one, so it
 * outweighs the default's `.dark` and the theme's own base; `.dark` inside a theme, under `:where`, weighs only as much
 * as the default's `.dark` and wins by coming later, so that a theme on the dark element itself outweighs a theme
 * around it. One case stays ambiguous: `.dark` on an element inside two nested themes takes the theme written later.
 * The density sits on the root, which the theme may be or be inside. */
function selectorsOf({ name }: ThemeInputs): Selectors {
  const theme = `[data-theme="${name}"]`;
  const comfortable = '[data-density="comfortable"]';
  return {
    base: theme,
    comfortable: `${theme}${comfortable},\n${comfortable} ${theme}`,
    dark: `${theme}.dark,\n.dark ${theme},\n:where(${theme}) .dark`,
  };
}

/** A theme's blocks: its tokens in each mode, and its control lengths in each density. Compact, the default density,
 * is the base, so a page that no script has touched shows it; `data-density="comfortable"` puts the comfortable
 * density's spacing unit and control lengths in its place. The radius, the focus ring and the shadows are variables
 * here, rather than values Tailwind writes into each utility, so that a theme can change them at run time. A theme other
 * than the default also declares its own values of the scales the default declares in `@theme`. */
function blocks(theme: ThemeInputs, selectors: Selectors, isDefault: boolean): string {
  const ownScales = isDefault ? "" : `${scaleDeclarations(theme)}\n`;
  return `${selectors.base} {
  color-scheme: light;
  --radius: ${theme.radius.base};
  --font-num: ${theme.fonts.num};
  --focus-width: ${theme.focus.width};
  --focus-offset: ${theme.focus.offset};
${shadowDeclarations(theme, "light")}
${ownScales}${controlDeclarations(theme, "compact")}
${tokenDeclarations(theme, "light")}
}

${selectors.dark} {
  color-scheme: dark;
${shadowDeclarations(theme, "dark")}
${tokenDeclarations(theme, "dark")}
}

/* The comfortable density widens the spacing unit, and every spacing utility with it, and sets its own control
   lengths. */
${selectors.comfortable} {
  --spacing: ${theme.spacing.comfortable};
${controlDeclarations(theme, "comfortable")}
}`;
}

/** One theme's own rules, under `[data-theme="NAME"]`, as every theme but the default is written: what the gallery's
 * studio puts on its page as the inputs change, over the shipped stylesheet's utilities, which read the variables. */
function scopedThemeCss(theme: ThemeInputs): string {
  return blocks(theme, selectorsOf(theme), false);
}

/** Tailwind's theme: only the theme's own values, and a colour utility for every token. The library's own scales, the
 * same in every theme, come first: the pill, the stacking order and WCAG 2.2's target size. Then the default's values
 * of a theme's scales, which every other theme's block declares again. */
function scales(theme: ThemeInputs): string {
  const colourMappings = Object.keys(tokensOf(theme))
    .map((name) => `  --color-${name}: var(--${name});`)
    .join("\n");
  return `/* Only the theme's own values exist: Tailwind's palette, its blur utilities and most of its shadows are removed, so a
   class that uses them is an unknown class and fails the lint. Citrix desktops draw on the CPU, where blur is slow.
   Each scale is named for its use: \`duration-popup\` and \`duration-panel\`, \`z-raised\` and \`z-popup\`,
   \`rounded-pill\` and \`opacity-disabled\`. */
@theme {
  --color-*: initial;
  --blur-*: initial;
  --shadow-*: initial;
  --inset-shadow-*: initial;
  --drop-shadow-*: initial;
  --text-shadow-*: initial;
  --radius-*: initial;
  --radius-pill: ${pillRadius};
  --z-index-raised: ${layers.raised};
  --z-index-popup: ${layers.popup};
  --spacing-target: ${targetSize};
${scaleDeclarations(theme)}
}

/* A bare \`outline\` or \`ring\` is the focus ring's width. A focus ring is
   \`outline-solid outline outline-offset-(--focus-offset) outline-ring\` under \`focus-visible:\`: an outline, whose
   offset is transparent on any surface and which Windows' forced colours keep. Its width and offset stay variables,
   since \`cn\` would take a named width for a second colour and drop it. */
@theme inline {
  --default-outline-width: var(--focus-width);
  --default-ring-width: var(--focus-width);
  --shadow-sm: var(--shadow-raised);
  --shadow-md: var(--shadow-floating);
${colourMappings}
}`;
}

/* Under reduced motion, from the operating system or the user's preference, nothing moves: every transition and
 * animation ends at once, the sidebar's slide and an accordion's opening among them. While the theme, mode or
 * density changes, nothing transitions at all: `applyPreferences` sets `data-switching` for the frame that shows the
 * change, so the page changes in one frame, as its canvases do, rather than cross-fading every control. */
const reducedMotion = `@media (prefers-reduced-motion: reduce) {
  *,
  ::before,
  ::after {
    animation-duration: 0.01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important;
  }
}

:root[data-motion="reduced"] *,
:root[data-motion="reduced"] ::before,
:root[data-motion="reduced"] ::after {
  animation-duration: 0.01ms !important;
  animation-iteration-count: 1 !important;
  transition-duration: 0.01ms !important;
}

:root[data-switching] *,
:root[data-switching] ::before,
:root[data-switching] ::after {
  transition: none !important;
}`;

/** The themes' own rules, plain CSS: the first theme is the default, at `:root`, and each other sits under
 * `[data-theme="name"]`, after it, each with its dark mode and its comfortable density. */
function themeBlocks(themes: readonly [ThemeInputs, ...ThemeInputs[]]): string {
  const [first, ...others] = themes;
  const names = new Set<string>();
  for (const { name } of themes) {
    if (names.has(name)) {
      throw new RangeError(`Two themes are named "${name}"; each needs a name of its own.`);
    }
    names.add(name);
  }
  return [
    blocks(first, defaultSelectors, true),
    ...others.map(
      (theme) =>
        `/* The ${theme.name} theme, under data-theme="${theme.name}" on the root or on a wrapper. */\n${blocks(theme, selectorsOf(theme), false)}`,
    ),
  ].join("\n\n");
}

/** The stylesheet for a set of themes, the default first: the themes' rules, and Tailwind's theme from the default. */
function themeCss(themes: readonly [ThemeInputs, ...ThemeInputs[]]): string {
  const [first] = themes;
  return `${[header, fontsAndVariant, themeBlocks(themes), scales(first), reducedMotion].join("\n\n")}\n`;
}

/** The module of the themes' names, `src/theme/theme-names.ts`, in their order, the default first: what the
 * preferences, the user menu and `vp run shot` know of the themes, without the inputs, which no app needs at run time. */
function themeNamesModule(themes: readonly [ThemeInputs, ...ThemeInputs[]]): string {
  const names = themes.map(({ name }) => JSON.stringify(name)).join(", ");
  return `// Written by \`vp run @basis/ui#theme\` from the themes in ./themes/index.ts: their names, in their order, the default
// first. The preferences, the user menu and \`vp run shot\` read these, so that no app ships the themes' inputs.

/** Every shipped theme's name, the default first. */
const themeNames = [${names}] as const;

export { themeNames };
`;
}

export { scopedThemeCss, tabularFace, themeBlocks, themeCss, themeNamesModule };

/* `vp run client-pull` writes `src/api/generated/formats.ts` beside orval's client: each number property's display
 * format, as the API's document declares it in `x-basis-format`, by its schema's name and the property's, so a page
 * shows `row.interest` by `displayFormats.CouponRow.interest` and never chooses decimals. A format this version does
 * not read, such as an unknown kind, is left out, and the value shows by the formatter's defaults. */

import { z } from "zod";

import { displayFormatSchema } from "#format/display-format.ts";
import type { DisplayFormat } from "#format/display-format.ts";

const schemasSchema = z.record(z.string(), z.unknown()).optional();
const componentsSchema = z.object({ schemas: schemasSchema }).optional();
const documentSchema = z.object({ components: componentsSchema });
const objectSchema = z.object({ properties: z.record(z.string(), z.unknown()) });

/** The display format a property's schema declares, on itself or on one of the members of its `anyOf`, as a
 * nullable number's schema holds it. */
function declaredFormat(property: unknown): DisplayFormat | undefined {
  const holder = z.object({ "x-basis-format": z.unknown() }).safeParse(property);
  if (holder.success) {
    const format = displayFormatSchema.safeParse(holder.data["x-basis-format"]);
    return format.success ? format.data : undefined;
  }
  const members = z.object({ anyOf: z.array(z.unknown()) }).safeParse(property);
  return members.success
    ? members.data.anyOf.map((member) => declaredFormat(member)).find(Boolean)
    : undefined;
}

/** Each schema's formatted properties, by name, in the document's order. */
function displayFormatsOf(document: unknown): Record<string, Record<string, DisplayFormat>> {
  const schemas = documentSchema.safeParse(document).data?.components?.schemas ?? {};
  const entries = Object.entries(schemas).flatMap(([name, schema]) => {
    const properties = objectSchema.safeParse(schema).data?.properties ?? {};
    const formats = Object.entries(properties).flatMap(([property, value]) => {
      const format = declaredFormat(value);
      return format === undefined ? [] : [[property, format] as const];
    });
    return formats.length === 0 ? [] : [[name, Object.fromEntries(formats)] as const];
  });
  return Object.fromEntries(entries);
}

/** The text of `formats.ts` for the document. */
function displayFormatsModule(document: unknown): string {
  const formats = JSON.stringify(displayFormatsOf(document), undefined, 2);
  return `/**
 * Generated by vp run client-pull from openapi.json's x-basis-format: each number property's display format, by its
 * schema and property. Do not edit; pull the document again.
 */
import type { DisplayFormat } from "@basis/ui";

export const displayFormats = ${formats} as const satisfies Readonly<
  Record<string, Readonly<Record<string, DisplayFormat>>>
>;
`;
}

export { displayFormatsModule, displayFormatsOf };
